HRESULT CRender::shader_compile(
'@
$text = Replace-ExactlyOnce $text $old $new "Action22 helper insertion seam"

# Dedicated tree alpha shaders must use generated cache entries while Action22
# is active. Otherwise an installed precompiled shader could bypass source
# compilation entirely and therefore bypass our source patch.
$old = @'
	string_path temp_file_name, file_name;
	bool const useGeneratedShaderCache =
		psDeviceFlags2.test(rsPrecompiledShaders) || !match_shader_id(name, sh_name, m_file_set, temp_file_name);
'@
$new = @'
	string_path temp_file_name, file_name;
	const bool optibridgeTreeAlpha = OptiBridge_IsTreeAlphaPixelShader(name, pTarget);
	bool const useGeneratedShaderCache =
		optibridgeTreeAlpha || psDeviceFlags2.test(rsPrecompiledShaders) ||
		!match_shader_id(name, sh_name, m_file_set, temp_file_name);
'@
$text = Replace-ExactlyOnce $text $old $new "Action22 generated-cache policy seam"

# Patch before getShaderSourceCrc32 so the injected strength becomes part of
# the source identity. Changing FloraAlphaWidthScale on the next game launch
# therefore causes a normal CRC mismatch/recompile rather than requiring the
# user to manually clear the shader cache.
$old = @'
	u32 source_crc = 0;
	if (useGeneratedShaderCache)
		source_crc = getShaderSourceCrc32(pSrcData, SrcDataLen, ::Render->getShaderPath());
'@
$new = @'
	xr_string optibridgePatchedSource;
	DWORD const* compileSrcData = pSrcData;
	UINT compileSrcDataLen = SrcDataLen;
	if (optibridgeTreeAlpha)
		OptiBridge_BuildTreeAlphaSource(name, compileSrcData, compileSrcDataLen, optibridgePatchedSource);

	u32 source_crc = 0;
	if (useGeneratedShaderCache)
		source_crc = getShaderSourceCrc32(compileSrcData, compileSrcDataLen, ::Render->getShaderPath());
'@
$text = Replace-ExactlyOnce $text $old $new "Action22 source CRC seam"

$old = @'
			D3DCompile(
				pSrcData,
				SrcDataLen,
'@
$new = @'
			D3DCompile(
				compileSrcData,
				compileSrcDataLen,
'@
$text = Replace-ExactlyOnce $text $old $new "Action22 D3DCompile source seam"

Set-Content $r4 $text -NoNewline
Write-Host "OptiBridge Action22 flora alpha-stability patch applied successfully."
