struct OptiBridgeFloraAlphaState
{
    bool loaded = false;
    bool enabled = false;
    bool logged = false;
    float widthScale = 0.25f;
};

OptiBridgeFloraAlphaState g_optibridgeFloraAlpha;

void OptiBridge_LoadFloraAlphaConfig()
{
    if (g_optibridgeFloraAlpha.loaded)
        return;

    char path[MAX_PATH] = {};
    GetModuleFileNameA(nullptr, path, MAX_PATH);
    char* slashA = strrchr(path, '\\');
    char* slashB = strrchr(path, '/');
    char* slash = slashA > slashB ? slashA : slashB;
    if (slash)
        *(slash + 1) = 0;
    strcat_s(path, "optibridge.ini");

    g_optibridgeFloraAlpha.enabled =
        GetPrivateProfileIntA("OptiBridge", "FloraAlphaStabilization", 0, path) != 0;

    char scaleText[32] = {};
    GetPrivateProfileStringA("OptiBridge", "FloraAlphaWidthScale", "0.25",
        scaleText, sizeof(scaleText), path);
    g_optibridgeFloraAlpha.widthScale = (float)atof(scaleText);
    g_optibridgeFloraAlpha.widthScale =
        _max(0.0f, _min(1.0f, g_optibridgeFloraAlpha.widthScale));
    g_optibridgeFloraAlpha.loaded = true;

    Msg("* [OptiBridge] Action22 flora alpha stabilization %s, derivative width scale %.3f",
        g_optibridgeFloraAlpha.enabled ? "on" : "off",
        g_optibridgeFloraAlpha.widthScale);
}

bool OptiBridge_IsTreeAlphaPixelShader(LPCSTR name, LPCSTR target)
{
    OptiBridge_LoadFloraAlphaConfig();
    if (!g_optibridgeFloraAlpha.enabled || !name || !target || target[0] != 'p')
        return false;

    LPCSTR base = name;
    if (LPCSTR slash = strrchr(name, '\\')) base = slash + 1;
    if (LPCSTR slash = strrchr(base, '/')) base = slash + 1;

    // SSS/GAMMA dedicated foliage alpha-test family. Deliberately do not
    // touch generic deffer_base_aref shaders used by fences/grates/etc.
    return 0 == strncmp(base, "deffer_tree_branch_aref_", 24);
}

void OptiBridge_BuildTreeAlphaSource(
    LPCSTR name,
    DWORD const*& source,
    UINT& sourceLength,
    xr_string& storage)
{
    char prefix[512] = {};
    xr_sprintf(prefix,
        "// OptiBridge Action22 tree alpha stabilization\n"
        "#define OPTIBRIDGE_FLORA_ALPHA_WIDTH_SCALE %.8ff\n"
        "#define clip(x) clip((x) + OPTIBRIDGE_FLORA_ALPHA_WIDTH_SCALE * fwidth(x))\n",
        g_optibridgeFloraAlpha.widthScale);

    storage.assign(prefix);
    storage.append(reinterpret_cast<LPCSTR>(source), sourceLength);
    source = reinterpret_cast<DWORD const*>(storage.data());
    sourceLength = (UINT)storage.size();

    if (!g_optibridgeFloraAlpha.logged)
    {
        Msg("* [OptiBridge] Action22 patching tree alpha shader source: %s", name);
        g_optibridgeFloraAlpha.logged = true;
    }
}
